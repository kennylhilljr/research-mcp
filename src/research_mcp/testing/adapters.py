"""A fake source adapter for tests, with its seven fixtures in memory (LLD-sources-v2 5.3).

Register it with ``SourceRegistry(..., extra_adapters=[(FAKE_SPEC, FakeAdapter)])`` so the
conformance suite and the registry tests run before any real adapter exists. The fake
speaks a small JSON API at ``https://api.fake-source.org`` and does all its I/O through
``ctx.http``, like a real adapter. ``FAKE_KIND_SPEC``, ``FakeInstance`` and
``fake_instance_spec`` make the same adapter an instance kind for discovery tests.
"""

import dataclasses
import functools
import json
from collections.abc import Sequence
from typing import Any, Literal
from urllib.parse import quote, urlsplit

from pydantic import BaseModel, ConfigDict

from research_mcp.core.errors import ErrorCode, HttpError
from research_mcp.core.ids import Identifier, normalize_doi
from research_mcp.core.models import (
    CitationPage,
    FulltextCandidate,
    ProbeResult,
    Provenance,
    SearchPage,
    SearchRequest,
    WorkRecord,
)
from research_mcp.core.specs import RateSpec
from research_mcp.sources.base import Capability, SourceContext, SourceSpec, translate_errors

ADAPTER_VERSION = "1"


@functools.cache
def _fake_spec() -> SourceSpec:
    return SourceSpec(
        id="fake",
        title="Fake source",
        group="scholarly",
        capabilities=frozenset({Capability.SEARCH, Capability.GET}),
        id_schemes=frozenset({"doi"}),
        hosts=frozenset({"api.fake-source.org"}),
        auth=None,
        rate=RateSpec(rps=10.0, burst=5, concurrency=2),
        max_page_size=25,
        max_bytes=16_384,
    )


@functools.cache
def _fake_kind_spec() -> SourceSpec:
    return dataclasses.replace(
        _fake_spec(), id="zz_kind", title="Fake repository kind", group="repositories"
    )


def __getattr__(name: str) -> SourceSpec:
    # The specs are built on first use: validating one at import would read the environment
    # (pydantic's plugin switch), and importing research_mcp does no work (PLAT-3).
    if name == "FAKE_SPEC":
        return _fake_spec()
    if name == "FAKE_KIND_SPEC":
        return _fake_kind_spec()
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


def _json(value: Any) -> bytes:
    return json.dumps(value).encode()


_ITEM = {"id": "F1", "title": "A fake work", "doi": "10.5555/Fake.1", "year": 2024}

FIXTURES: dict[str, tuple[str, bytes]] = {
    "search_ok": ("search_ok.json", _json({"total": 1, "next": None, "results": [_ITEM]})),
    "search_empty": ("search_empty.json", _json({"total": 0, "next": None, "results": []})),
    "get_ok": ("get_ok.json", _json(_ITEM)),
    "err_429": ("err_429.json", _json({"status": 429, "headers": {"Retry-After": "2"}})),
    "err_5xx": ("err_5xx.json", _json({"status": 503, "headers": {}, "body": "unavailable"})),
    # Valid JSON in the wrong shape: the mapping fails and translate_errors reports it.
    "malformed": ("malformed.json", _json({"results": [{"id": 17, "name": "no title"}]})),
    "oversize.marker": ("oversize.marker", b"generated by the conformance suite\n"),
}


class FakeInstance(BaseModel):
    """Settings of one instance of the fake kind."""

    model_config = ConfigDict(strict=True, extra="forbid", defer_build=True)

    base_url: str
    title: str


def fake_instance_spec(base: SourceSpec, instance_id: str, cfg: BaseModel) -> SourceSpec:
    if not isinstance(cfg, FakeInstance):
        raise TypeError("expected FakeInstance settings")
    host = urlsplit(cfg.base_url).hostname or ""
    return dataclasses.replace(
        base, id=instance_id, title=cfg.title, hosts=frozenset({host}), instance_of=base.id
    )


class FakeAdapter:
    """Translates the fake JSON API; it sleeps, retries and reads secrets never."""

    FIXTURES = FIXTURES

    def __init__(self, spec: SourceSpec, ctx: SourceContext) -> None:
        self.spec = spec
        self.ctx = ctx

    def url(self, path: str) -> str:
        return f"https://{min(self.spec.hosts)}{path}"

    def record(self, item: dict[str, Any]) -> WorkRecord:
        return WorkRecord(
            ids=[Identifier("doi", normalize_doi(item["doi"]))],
            title=item["title"],
            year=item.get("year"),
            provenance=Provenance(
                source=self.spec.id,
                upstream_id=item["id"],
                adapter_version=ADAPTER_VERSION,
                retrieved_at=self.ctx.clock.now(),
            ),
        )

    @translate_errors
    async def search(self, req: SearchRequest) -> SearchPage:
        params = {"q": req.query, "limit": str(min(req.limit, self.spec.max_page_size))}
        if req.cursor:
            params["cursor"] = req.cursor
        data: Any = await self.ctx.http.get_json(
            self.url("/search"), source=self.spec.id, params=params
        )
        return SearchPage(
            records=[self.record(item) for item in data["results"]],
            total=data["total"],
            next_cursor=data["next"],
        )

    @translate_errors
    async def get(self, ident: Identifier) -> WorkRecord | None:
        try:
            data: Any = await self.ctx.http.get_json(
                self.url("/works/" + quote(ident.value, safe="")), source=self.spec.id
            )
        except HttpError as exc:
            if exc.code is ErrorCode.NOT_FOUND:
                return None
            raise
        return self.record(data)

    async def fulltext_candidates(self, work: WorkRecord) -> list[FulltextCandidate]:
        return [
            FulltextCandidate(location=location, priority=index)
            for index, location in enumerate(work.oa_locations)
        ]

    async def citations(
        self,
        ident: Identifier,
        direction: Literal["citing", "cited"],
        cursor: str | None,
        limit: int,
    ) -> CitationPage:
        return CitationPage(ids=[])

    async def search_authors(
        self, query: str | None, orcid: str | None, limit: int
    ) -> Sequence[BaseModel]:
        return []

    async def updates(self, ident: Identifier) -> Sequence[BaseModel]:
        return []

    async def probe(self) -> ProbeResult:
        started = self.ctx.clock.now()
        try:
            data: Any = await self.ctx.http.get_json(self.url("/works/probe"), source=self.spec.id)
        except HttpError as exc:
            return ProbeResult(ok=False, latency_ms=0, shape_ok=False, detail_code=exc.code.value)
        elapsed = self.ctx.clock.now() - started
        shape_ok = (
            isinstance(data, dict)
            and isinstance(data.get("id"), str)
            and isinstance(data.get("title"), str)
        )
        return ProbeResult(
            ok=True, latency_ms=int(elapsed.total_seconds() * 1000), shape_ok=shape_ok
        )
