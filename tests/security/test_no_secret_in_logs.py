"""No secret in any log output: the structured file and stderr (SEC-INV-4; test plan v4 1.2).

Every secret here is generated by the test and registered with the redactor, as the
security suite requires; no real credential is read.
"""

from __future__ import annotations

import io
import logging
import os
from collections.abc import Iterator
from pathlib import Path

import pytest
from hypothesis import HealthCheck, given
from hypothesis import settings as hsettings
from hypothesis import strategies as st

from research_mcp.platform.logging import configure_logging
from research_mcp.platform.secrets import Secret, SecretRef
from research_mcp.settings import Settings

SECRET_ALPHABET = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_."
NAMES = ("CORE_API_KEY", "GITHUB_TOKEN", "DAEMON_TOKEN", "NCBI_API_KEY", "ZENODO_TOKEN")

# Like real keys, each value mixes cases and digits, so it cannot equal fixed text such as
# a logger name, a timestamp or a hex hash that legitimately appears in every line.
secret_values = st.text(SECRET_ALPHABET, min_size=12, max_size=64).filter(
    lambda v: (
        any(c.isdigit() for c in v) and any(c.isupper() for c in v) and any(c.islower() for c in v)
    )
)


@pytest.fixture(autouse=True)
def isolated(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Iterator[io.StringIO]:
    monkeypatch.setenv("HOME", str(tmp_path))
    for name in os.environ:
        if name.startswith("RESEARCH_MCP_"):
            monkeypatch.delenv(name)
    stderr = io.StringIO()
    monkeypatch.setattr("sys.stderr", stderr)
    root = logging.getLogger()
    saved_handlers = root.handlers[:]
    saved_filters = {id(h): h.filters[:] for h in saved_handlers}
    names = ("research_mcp", "httpx", "httpcore", "uvicorn.access", "mcp")
    saved_levels = {name: logging.getLogger(name).level for name in names}
    saved_root = root.level
    yield stderr
    root.setLevel(saved_root)
    for handler in root.handlers[:]:
        if handler not in saved_handlers:
            root.removeHandler(handler)
            handler.close()
    for handler in saved_handlers:
        handler.filters[:] = saved_filters[id(handler)]
    for name, level in saved_levels.items():
        logging.getLogger(name).setLevel(level)


class Output:
    """Everything written to the log file and stderr since the last call."""

    def __init__(self, log_file: Path, stderr: io.StringIO) -> None:
        self.log_file = log_file
        self.stderr = stderr
        self.file_offset = 0
        self.stderr_offset = 0

    def new_text(self) -> str:
        for handler in logging.getLogger().handlers:
            handler.flush()
        data = self.log_file.read_bytes() if self.log_file.exists() else b""
        file_text = data[self.file_offset :].decode()
        self.file_offset = len(data)
        stderr_text = self.stderr.getvalue()[self.stderr_offset :]
        self.stderr_offset = len(self.stderr.getvalue())
        return file_text + stderr_text


def emit_everywhere(secret: str, debug_query: bool) -> None:
    """Log the value through every path a record can carry text."""
    log = logging.getLogger("research_mcp.services.search")
    log.warning("in message %s", secret)
    log.warning("split %s%s", secret[:5], secret[5:])
    log.error("in extra", extra={"source": secret, "headers": {"X-Api-Key": secret}})
    log.warning("in query", extra={"query": f"papers about {secret}"})
    if debug_query:
        log.debug("debug query", extra={"query": secret})
    try:
        raise RuntimeError(f"upstream said {secret!r}")
    except RuntimeError:
        log.exception("tool.internal")
    logging.getLogger("some_library").warning("library %r", {"token": secret})
    logging.getLogger("httpx").warning("GET https://h.example/x?api_key=%s", secret)
    logging.getLogger("httpx").info("GET https://h.example/x?q=%s", secret)


@pytest.mark.parametrize("debug", [False, True])
def test_registered_secrets_never_reach_log_output(
    tmp_path: Path, isolated: io.StringIO, debug: bool
) -> None:
    """@spec SEC-7: Random secrets registered with the redactor are in no formatted record."""
    config = Settings(paths={"log_dir": tmp_path / "logs"}, logging={"debug": debug})
    redactor = configure_logging(config)
    output = Output(tmp_path / "logs" / "research-mcp.jsonl", isolated)

    @hsettings(
        max_examples=60,
        deadline=None,
        suppress_health_check=[HealthCheck.function_scoped_fixture],
    )
    @given(values=st.lists(secret_values, min_size=1, max_size=len(NAMES), unique=True))
    def check(values: list[str]) -> None:
        for name, value in zip(NAMES, values, strict=False):
            redactor.register(Secret(SecretRef.parse(f"keychain:research-mcp/{name}"), value))
        for value in values:
            emit_everywhere(value, debug)
        text = output.new_text()
        assert text, "the records must reach the outputs being scanned"
        for value in values:
            assert value not in text

    check()


def test_pattern_credentials_never_reach_log_output(tmp_path: Path, isolated: io.StringIO) -> None:
    """@spec SEC-6: Credential patterns that were never registered are masked in log output."""
    configure_logging(Settings(paths={"log_dir": tmp_path / "logs"}))
    output = Output(tmp_path / "logs" / "research-mcp.jsonl", isolated)
    hidden = "zq81Unregistered7Value"
    log = logging.getLogger("research_mcp.platform.http")
    log.warning("GET https://core.example/v3?key=%s", hidden)
    log.warning("headers %r", {"Authorization": f"Bearer {hidden}"})
    log.warning("X-Subscription-Token: %s", hidden)
    log.warning("sent AIza%s and ghp_%s and github_pat_%s", hidden, hidden, hidden)
    text = output.new_text()
    assert text
    assert hidden not in text


def test_third_party_info_with_api_key_is_dropped(tmp_path: Path, isolated: io.StringIO) -> None:
    """@spec SEC-14: An INFO httpx record carrying api_key in its URL is never written."""
    logging.getLogger().setLevel(logging.DEBUG)  # the quiet levels must not rely on the root
    configure_logging(Settings(paths={"log_dir": tmp_path / "logs"}))
    output = Output(tmp_path / "logs" / "research-mcp.jsonl", isolated)
    logging.getLogger("httpx").info(
        'HTTP Request: GET https://api.example/v1?api_key=%s "HTTP/1.1 200 OK"', "rawKey123456"
    )
    logging.getLogger("httpcore.http11").info("send_request_headers.started")
    logging.getLogger("uvicorn.access").info('127.0.0.1 - "POST /mcp?token=x" 200')
    logging.getLogger("mcp.server").info("Processing request")
    assert output.new_text() == ""


def test_secret_registered_after_configuration_is_masked(
    tmp_path: Path, isolated: io.StringIO
) -> None:
    """@spec SEC-5: A value registered at load or reload is masked from the next record on."""
    redactor = configure_logging(Settings(paths={"log_dir": tmp_path / "logs"}))
    output = Output(tmp_path / "logs" / "research-mcp.jsonl", isolated)
    value = "tv-7d1e5a90c3-rel"
    redactor.register(Secret(SecretRef.parse("keychain:research-mcp/GITHUB_TOKEN"), value))
    emit_everywhere(value, debug_query=False)
    text = output.new_text()
    assert text
    assert value not in text
