"""No registered secret at rest after install, a daemon start and a reload (SEC-INV-3).

The test runs the real entry points, ``research-mcp install`` and ``research-mcpd``, in a
home folder under ``tmp_path``, with a ``FakeProvider`` in place of the Keychain and a fake
launchd. Only the uvicorn bind is replaced: the app's lifespan runs in full, so the stores,
the migrations, the scheduler and the logs write what a real start writes. Every secret is
generated by the test; no real credential is read (LLD-platform-v2 4.7).
"""

from __future__ import annotations

import io
import logging
import os
import secrets
import sys
from collections.abc import Iterator
from pathlib import Path
from typing import Any

import httpx
import pytest

from research_mcp import app as app_module
from research_mcp import cli, daemon
from research_mcp.platform import auth
from research_mcp.platform.secrets import FakeProvider
from research_mcp.settings import Settings
from research_mcp.testing.launchctl import FakeLaunchctl

BASE = "http://127.0.0.1:7319"
WEBHOOK = "https://hooks.research-mcp.dev/notify"

# Every Keychain item the platform LLD names (4.1), except DAEMON_TOKEN, which install mints.
REGISTERED = (
    "NOTIFY_WEBHOOK_TOKEN",
    "OPENALEX_API_KEY",
    "SEMANTIC_SCHOLAR_API_KEY",
    "CORE_API_KEY",
    "GOOGLE_DEVKNOWLEDGE_API_KEY",
    "GITHUB_TOKEN",
    "ZENODO_TOKEN",
    "NCBI_API_KEY",
    "NVD_API_KEY",
    "ADS_API_TOKEN",
    "LENS_API_TOKEN",
    "OPENCITATIONS_TOKEN",
    "BRAVE_SEARCH_API_KEY",
    "SERPAPI_API_KEY",
)


def fake_value(name: str) -> str:
    return f"sec24-{name.lower()}-{secrets.token_urlsafe(24)}"


@pytest.fixture
def home(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Iterator[Path]:
    """A home folder of its own, no settings overrides, and the logging state restored."""
    monkeypatch.setenv("HOME", str(tmp_path))
    for name in os.environ:
        if name.startswith("RESEARCH_MCP_"):
            monkeypatch.delenv(name)
    monkeypatch.setattr(sys, "stderr", io.StringIO())  # the daemon wraps sys.stderr
    root = logging.getLogger()
    saved_handlers = root.handlers[:]
    saved_filters = {id(h): h.filters[:] for h in saved_handlers}
    names = ("research_mcp", "httpx", "httpcore", "uvicorn.access", "mcp")
    saved_levels = {name: logging.getLogger(name).level for name in names}
    last_resort = logging.lastResort
    saved_last_resort = last_resort.filters[:] if last_resort else []
    yield tmp_path
    if last_resort:
        last_resort.filters[:] = saved_last_resort
    for handler in root.handlers[:]:
        if handler not in saved_handlers:
            root.removeHandler(handler)
            handler.close()
    for handler in saved_handlers:
        handler.filters[:] = saved_filters[id(handler)]
    for name, level in saved_levels.items():
        logging.getLogger(name).setLevel(level)


def write_config(home: Path) -> Path:
    """``config.toml`` as the owner writes it: references only, a tokenless webhook URL."""
    config_dir = home / ".config" / "research-mcp"
    config_dir.mkdir(mode=0o700, parents=True)
    config = config_dir / "config.toml"
    config.write_text(
        '[server]\ntoken = "keychain:research-mcp/DAEMON_TOKEN"\n\n'
        f'[notify]\nwebhook_url = "{WEBHOOK}"\n',
        encoding="utf-8",
    )
    return config


def files_under(*folders: Path) -> list[Path]:
    return sorted(path for folder in folders for path in folder.rglob("*") if path.is_file())


def test_config_and_state_db_hold_no_secret(home: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """@spec SEC-24: after install, a daemon start and a reload with registered fake secrets,
    no registered value is in any file of the config or Application Support folders."""
    config = write_config(home)
    provider = FakeProvider({name: fake_value(name) for name in REGISTERED})
    launchctl = FakeLaunchctl(loaded=False)
    monkeypatch.setattr(cli, "KeychainProvider", lambda _user: provider)
    monkeypatch.setattr(cli, "SystemLaunchctl", lambda: launchctl)
    monkeypatch.setattr(cli, "default_venv_root", lambda: home / "venv")
    monkeypatch.setattr(app_module, "KeychainProvider", lambda _user: provider)

    # install: renders the plists, creates the folders and mints DAEMON_TOKEN.
    assert cli.main(["install", "--print-client-config"]) == 0
    first_token = provider.items[auth.DAEMON_TOKEN]
    assert len(launchctl.starts) == 3

    # A daemon start, then a rotation and the reload it triggers (PLAT-FR-15, PLAT-FR-59).
    seen: dict[str, Any] = {}

    async def serve_in_process(app: Any, settings: Settings) -> None:
        async with app.router.lifespan_context(app):
            runtime = app.state.runtime
            seen["refs"] = set(runtime.refs)
            async with httpx.AsyncClient(
                transport=httpx.ASGITransport(app=app), base_url=BASE
            ) as client:
                headers = {"Authorization": f"Bearer {first_token}"}
                assert (await client.get("/api/status", headers=headers)).status_code == 200

                provider.items["OPENALEX_API_KEY"] = fake_value("OPENALEX_API_KEY")
                assert await cli.rotate_token(settings, provider, FakeLaunchctl()) == 0
                changed = await app.state.reload_credentials()
                seen["changed"] = set(changed)

                headers = {"Authorization": f"Bearer {provider.items[auth.DAEMON_TOKEN]}"}
                assert (await client.get("/api/status", headers=headers)).status_code == 200
            await runtime.state.flush()

    monkeypatch.setattr(daemon, "serve", serve_in_process)
    assert daemon.main() == 0
    assert {auth.DAEMON_TOKEN, "OPENALEX_API_KEY"} <= seen["changed"] <= seen["refs"]

    registered = {"DAEMON_TOKEN (minted)": first_token, **provider.items}
    assert len(set(registered.values())) == len(REGISTERED) + 2

    app_support = home / "Library" / "Application Support" / "research-mcp"
    assert Settings().paths.state_dir == app_support.resolve()
    # The whole home folder: the config and Application Support folders, and also the
    # logs and the plists, which SEC-INV-3 covers too.
    scanned = files_under(home)
    assert config in scanned
    assert app_support / "state.db" in scanned
    assert app_support / "cache" / "cache.db" in scanned
    assert home / "Library" / "Logs" / "research-mcp" / "research-mcp.jsonl" in scanned

    # Names only in the failure message, never the values.
    leaks = [
        (str(path.relative_to(home)), name)
        for path in scanned
        for name, value in registered.items()
        if value.encode() in path.read_bytes()
    ]
    assert leaks == []
