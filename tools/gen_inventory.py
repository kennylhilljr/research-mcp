"""Writes docs/generated/sources.md from the registered adapters (LLD-sources-v2 5.10).

The registry is built with default settings and the default adapters; no Keychain and no
network is touched. `--check` fails (exit 1) when the committed file differs from the
generated text (SRC-FR-25; SRC-13; NFR-10)."""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from research_mcp.settings import Settings  # noqa: E402
from research_mcp.sources.base import SourceContext, SourceSpec  # noqa: E402
from research_mcp.sources.registry import RegisteredSource, SourceRegistry, SourceView  # noqa: E402

OUTPUT = ROOT / "docs/generated/sources.md"

HEADER = (
    "# Source inventory\n\n"
    "Generated by `tools/gen_inventory.py`; do not edit by hand (SRC-FR-25). "
    "Run `uv run python tools/gen_inventory.py` after changing a source's `SourceSpec`.\n\n"
    "| id | title | group | capabilities | auth | rate | hosts | extras | "
    "default state | probe | shutdown |\n"
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n"
)


class _DefaultSettings(Settings):
    """Pure defaults: the inventory never reads this machine's config.toml or environment."""

    @classmethod
    def settings_customise_sources(cls, settings_cls, init_settings, **_rest):
        return (init_settings,)


def _ctx_factory(spec: SourceSpec) -> SourceContext:
    raise NotImplementedError("the inventory never calls an adapter")


def _auth_cell(spec: SourceSpec) -> str:
    if spec.auth is None:
        return "none"
    names = ", ".join(f"`{name}`" for name in spec.auth.secrets)
    return f"{names} ([signup]({spec.auth.signup_url}))"


def _rate_cell(spec: SourceSpec) -> str:
    rate = spec.rate
    cell = f"{rate.rps:.3g}/s, burst {rate.burst}, concurrency {rate.concurrency}"
    if rate.daily_quota is not None:
        cell += f", daily quota {rate.daily_quota}"
    return cell


def _row(source: RegisteredSource, view: SourceView) -> str:
    spec = source.spec
    capabilities = ", ".join(sorted(c.value for c in spec.capabilities))
    hosts = ", ".join(sorted(spec.hosts))
    extras = ", ".join(sorted(spec.extras)) or "none"
    probe = f"every {spec.probe.cadence_s}s, {spec.probe.cost}"
    shutdown = spec.shutdown_on.isoformat() if spec.shutdown_on else ""
    return (
        f"| {spec.id} | {spec.title} | {spec.group} | {capabilities} | {_auth_cell(spec)} | "
        f"{_rate_cell(spec)} | {hosts} | {extras} | {view.state} | {probe} | {shutdown} |"
    )


def render() -> str:
    settings = _DefaultSettings()
    registry = SourceRegistry(settings, _ctx_factory, has_credential=lambda name: False)
    views = {view.id: view for view in registry.view()}
    rows = "\n".join(_row(source, views[source.spec.id]) for source in registry.all())
    return HEADER + rows + "\n"


# @spec SRC-13
def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is stale; run `uv run python tools/gen_inventory.py`", file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
